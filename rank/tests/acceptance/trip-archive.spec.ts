import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { archiveKey, createArchive, encryptTrips, unlockArchive } from '../../src/utils/tripArchive'

const password = 'private-test-passphrase-2026'
const privateName = '私密行程测试标记'
const privateAddress = '自填地址安全验收标记'
const privateNote = '私有备注不应进入请求或普通存储'
const requests = new WeakMap<object, string[]>()
test.beforeEach(async ({ page, context, baseURL }) => {
  expect(new URL(baseURL!).hostname).toBe('127.0.0.1')
  requests.set(page, [])
  context.on('request', request => requests.get(page)!.push(request.url() + (request.postData() || '')))
  await context.route('**/*', route => new URL(route.request().url()).origin === new URL(baseURL!).origin ? route.continue() : route.abort())
})
test.afterEach(async ({ page }) => {
  for (const secret of [password, privateName, privateAddress, privateNote]) {
    for (const request of requests.get(page)!) { expect(request).not.toContain(secret); expect(request).not.toContain(encodeURIComponent(secret)) }
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

