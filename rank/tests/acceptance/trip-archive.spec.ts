test('存储失败不降级为明文，恶意文件被拒绝而不会执行或清空当前清单', async ({ page }) => {
  await page.goto('')
  await page.locator('.trip-plan-entry').getByRole('button', { name: '开始选店', exact: true }).click()
  await page.locator('.place-card .trip-plan-add').first().click()
  await page.getByRole('button', { name: '查看清单', exact: true }).click()
  await page.getByRole('button', { name: '保存／恢复行程', exact: true }).click()
  const archive = page.getByRole('dialog', { name: '本机保存的行程', exact: true })
  await archive.getByLabel('设置独立口令（12—128个字符）', { exact: true }).fill(password)
  await archive.getByLabel('再次输入口令', { exact: true }).fill(password)
  await archive.getByRole('button', { name: '开始使用加密保存', exact: true }).click()
  await page.evaluate(key => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (name, value) { if (name === key) throw new DOMException('quota', 'QuotaExceededError'); return original.call(this, name, value) }
  }, archiveKey)
  await archive.getByLabel('本次行程名称', { exact: true }).fill(privateName)
  await archive.getByRole('button', { name: '保存本次行程', exact: true }).click()
  await expect(archive.getByRole('alert')).toContainText('保存失败')
  expect(await page.evaluate(key => localStorage.getItem(key), archiveKey)).toBeNull()
  await archive.getByLabel('选择加密备份文件').setInputFiles({ name: 'malicious.json', mimeType: 'application/json', buffer: Buffer.from('<script>window.archiveAttack=1</script>') })
  await expect(archive.getByRole('alert')).toContainText('请选择本站导出')
  expect(await page.evaluate(() => (window as any).archiveAttack)).toBeUndefined()
  await archive.getByRole('button', { name: '关闭本机行程', exact: true }).click()
  await expect(page.locator('.trip-plan-dock')).toContainText('1 站')
})

test('恢复保留过期条目并标明原因，闲置自动锁定，多个标签页不会静默覆盖', async ({ page }) => {
  const key = await createArchive(password)
  const trip = { id: 'review-test', name: '过期活动原计划', savedAt: '2026-10-01T04:00:00Z', entries: [{ placeId: 'removed-place', shopName: '旧活动' }], labels: ['旧活动'], preferences: { modes: {}, visits: {} } }
  const raw = JSON.stringify(await encryptTrips([trip], key.key, key.salt))
  await page.clock.install({ time: new Date('2026-11-02T04:00:00Z') })
  await page.goto('')
  await page.evaluate(({ key, raw }) => localStorage.setItem(key, raw), { key: archiveKey, raw })
  await page.getByRole('button', { name: '本机行程', exact: true }).click()
  const archive = page.getByRole('dialog', { name: '本机保存的行程', exact: true })
  const unlock = async () => {
    await archive.getByLabel('解锁口令', { exact: true }).fill(password)
    await archive.getByRole('button', { name: '解锁行程', exact: true }).click()
    await expect(archive.locator('.archive-list')).toContainText('过期活动原计划')
  }
  await unlock()
  await page.clock.fastForward(5 * 60000 + 1)
  await expect(archive.locator('.archive-list')).toHaveCount(0)
  await unlock()
  await page.evaluate(key => localStorage.setItem(key, 'changed-by-another-tab'), archiveKey)
  await archive.getByRole('button', { name: '重命名', exact: true }).click()
  await archive.getByLabel('新的行程名称').fill('不能覆盖')
  await archive.getByRole('button', { name: '保存名称', exact: true }).click()
  await expect(archive.getByRole('alert')).toContainText('另一标签页')
  expect(await page.evaluate(key => localStorage.getItem(key), archiveKey)).toBe('changed-by-another-tab')
  await archive.getByRole('button', { name: '查看并恢复', exact: true }).click()
  await expect(archive.locator('.archive-review')).toContainText('地点已移除或暂不公开')
  await archive.getByRole('button', { name: '恢复到想逛清单', exact: true }).click()
  await expect(page.locator('.trip-plan-unavailable')).toContainText('旧活动')
  expect(await page.evaluate(() => sessionStorage.getItem('tangbao-trip-plan-session-v1'))).toContain('旧活动')
})
