import { test, expect } from '@playwright/test'
import { mkdirSync, readFileSync } from 'node:fs'

const fixture = 'http://127.0.0.1:4174/bltbSch_201.github.io/rank/'
const production = 'http://127.0.0.1:4173/bltbSch_201.github.io/rank/'
mkdirSync('test-results/evidence', { recursive: true })

for (const width of [390, 1440]) {
  test(`temporary trip selections survive navigation, reorder and export only selected stops at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 950 })
    await page.clock.install({ time: new Date('2026-10-29T04:00:00Z') })
    await page.goto(fixture)
    await page.locator('#place-card-demo-0').getByRole('button', { name: /加入本次清单/ }).click()
    await page.locator('#place-card-demo-1').getByRole('button', { name: /加入本次清单/ }).click()
    await expect(page.locator('.trip-plan-dock')).toContainText('2 站')
    await page.getByLabel('城市筛选').selectOption('测试甲城')
    await expect(page.locator('.trip-plan-dock')).toContainText('2 站')
    await page.locator('#place-card-demo-0 .card-link').click()
    const shop = page.locator('.shop-row').filter({ has: page.getByRole('heading', { name: '测试常设店', exact: true }) })
    await shop.getByRole('button', { name: '加入本次清单：测试常设店', exact: true }).click()
    await expect(page.locator('.trip-plan-dock')).toContainText('3 站')
    await page.goBack()
    await expect(page.locator('.trip-plan-dock')).toContainText('3 站')
    await page.goForward()
    await expect(page.locator('.trip-plan-dock')).toContainText('3 站')
    await page.reload()
    await expect(page.locator('.trip-plan-dock')).toContainText('3 站')
    await page.getByRole('button', { name: '整理与导出', exact: true }).click()
    const planner = page.locator('.trip-plan-dialog')
    await planner.getByRole('button', { name: '上移：测试常设店', exact: true }).click()
    await expect(planner.locator('h3').nth(1)).toHaveText('测试常设店')
    await expect(planner.locator('.trip-plan-stop').first().getByRole('button', { name: /上移/ })).toBeDisabled()
    await expect(planner.locator('.trip-plan-stop').last().getByRole('button', { name: /下移/ })).toBeDisabled()
    await expect(planner).toContainText('负一层')
    await planner.getByRole('button', { name: '生成清单文件', exact: true }).click()
    const downloadPromise = page.waitForEvent('download')
    await planner.getByRole('link', { name: '下载清单（HTML）' }).click()
    const download = await downloadPromise
    const file = await download.path()
    const html = readFileSync(file!, 'utf8')
    expect(html).toContain('3 站')
    expect(html).toContain('负一层')
    expect(html).toContain('虚构测试地址，仅用于功能验证')
    expect(html.indexOf('<h2>测试常设店</h2>')).toBeLessThan(html.indexOf('<h2>虚构店铺 1（演示）</h2>'))
    expect(html).not.toContain('虚构店铺 27（演示）')
    await planner.getByRole('button', { name: '导出所选地点榜单', exact: true }).click()
    await expect(page.locator('.export-dialog')).toBeVisible()
    await expect(page.getByLabel('本次清单 · 2 处地点')).toBeChecked()
    await page.getByRole('button', { name: '关闭导出', exact: true }).click()
    await expect(planner).toBeVisible()
    expect(await planner.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await planner.getByRole('button', { name: '清空本次清单', exact: true }).click()
    await expect(page.locator('.trip-plan-dock')).toHaveCount(0)
    await page.reload()
    await expect(page.locator('.trip-plan-dock')).toHaveCount(0)
    expect(await page.evaluate(() => localStorage.getItem('tangbao-trip-plan-session-v1'))).toBeNull()
  })
}

test('the actual shop list supplies addresses and floors to the temporary plan', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.clock.install({ time: new Date('2026-10-29T04:00:00Z') })
  await page.goto(production + 'guide/#/place/guangzhou-shop-003')
  await page.locator('.detail-heading').getByRole('button', { name: /加入本次清单/ }).click()
  const firstShop = page.locator('.shop-directory-regular .shop-row').first()
  const name = await firstShop.locator('h4').innerText()
  await firstShop.getByRole('button', { name: `加入本次清单：${name}`, exact: true }).click()
  await page.getByRole('button', { name: '整理与导出', exact: true }).click()
  await expect(page.locator('.trip-plan-stop')).toHaveCount(2)
  await expect(page.locator('.trip-plan-dialog')).toContainText(name)
  await page.locator('.trip-plan-dialog').screenshot({ path: 'test-results/evidence/trip-plan-preview.png' })
})
