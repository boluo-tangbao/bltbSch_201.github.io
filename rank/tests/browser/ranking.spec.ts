test('fixture: export real images, Chinese, long names, filtered scope, pagination and retry', async ({ page }) => {
  await page.goto(fixture)
  await page.getByRole('button', { name: '导出榜单' }).click()
  await page.getByLabel('短评长图 · 加上一句话评价').check()
  await page.getByRole('button', { name: '生成图片', exact: true }).click()
  await expect(page.locator('.download-list a').first()).toBeVisible()
  const links = page.locator('.download-list a'), count = await links.count()
  expect(count).toBeGreaterThan(1)
  for (let i = 0; i < count; i++) {
    const download = page.waitForEvent('download'); await links.nth(i).click(); await (await download).saveAs(`test-results/evidence/fixture-review-${i + 1}.png`)
  }
  await page.getByLabel('简洁排序图 · 图片与名称').check(); await page.getByRole('button', { name: '重新生成' }).click()
  await expect(links.first()).toBeVisible()
  let download = page.waitForEvent('download'); await links.first().click(); await (await download).saveAs('test-results/evidence/fixture-compact.png')
  await page.getByRole('button', { name: '关闭导出' }).click()
  await page.getByRole('searchbox').fill('店铺 1（')
  await expect(page.locator('.place-card')).toHaveCount(1)
  await page.getByRole('button', { name: '导出榜单' }).click()
  await page.getByRole('button', { name: '生成图片', exact: true }).click()
  await expect(links).toHaveCount(1)
  download = page.waitForEvent('download'); await links.click(); await (await download).saveAs('test-results/evidence/filtered.png')
  await page.getByRole('button', { name: '关闭导出' }).click()
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await page.route('**/images/places/test.svg', route => route.abort())
  await page.getByRole('button', { name: '导出榜单' }).click(); await page.getByRole('button', { name: '生成图片', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('图片加载失败')
  await page.unroute('**/images/places/test.svg')
  await page.getByRole('button', { name: '生成图片', exact: true }).click(); await expect(links.first()).toBeVisible()
})
