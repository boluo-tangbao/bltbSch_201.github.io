import { test, expect, type Page } from '@playwright/test'
import { mkdirSync } from 'node:fs'
const empty = 'http://127.0.0.1:4175/jimmyGu.github.io/rank/'
const fixture = 'http://127.0.0.1:4174/jimmyGu.github.io/rank/'
mkdirSync('test-results/evidence', { recursive: true })
async function noOverflow(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true) }
test('empty board: responsive layout, filters, invalid detail, exports', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto(empty)
  await expect(page.locator('.tier-label h3')).toHaveText(['夯', '顶级', '人上人', 'NPC', '拉完了'])
  await expect(page.locator('.tier-empty')).toHaveCount(5)
  await expect(page.locator('.place-card')).toHaveCount(0)
  for (const width of [1440, 768, 375]) {
    await page.setViewportSize({ width, height: 1000 }); await noOverflow(page)
    await page.screenshot({ path: `test-results/evidence/empty-${width}.png`, fullPage: true })
  }
  await page.getByRole('searchbox').fill('不存在')
  await expect(page.getByText('没有找到匹配的条目')).toBeVisible()
  await page.reload(); await expect(page.getByRole('searchbox')).toHaveValue('不存在')
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await expect(page.getByRole('searchbox')).toHaveValue('')
  await page.goto(empty + '#/place/missing'); await expect(page.getByRole('heading', { name: '没有找到这个条目' })).toBeVisible()
  await page.reload(); await expect(page.getByRole('heading', { name: '没有找到这个条目' })).toBeVisible()
  await page.getByRole('link', { name: '返回榜单', exact: true }).click()
  await page.getByRole('button', { name: '导出榜单' }).click()
  await page.getByRole('button', { name: '生成图片', exact: true }).click()
  await expect(page.locator('.download-list a')).toHaveCount(1)
  let download = page.waitForEvent('download'); await page.locator('.download-list a').click(); await (await download).saveAs('test-results/evidence/empty-compact.png')
  await page.getByLabel('短评长图 · 加上一句话评价').check()
  await page.getByRole('button', { name: '重新生成' }).click()
  await expect(page.locator('.download-list a')).toHaveCount(1)
  download = page.waitForEvent('download'); await page.locator('.download-list a').click(); await (await download).saveAs('test-results/evidence/empty-review.png')
  await page.keyboard.press('Escape'); await expect(page.locator('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '导出榜单' })).toBeFocused()
  expect(errors).toEqual([])
})
